def test_batch_matches_id_and_timestamps_before_decode():
    client = object.__new__(Client)
    client.serial = 0
    client.pending = []
    client.messages = queue.Queue()
    messages = [
        {"id": 999, "result": "old response"},
        {"method": "textDocument/publishDiagnostics", "params": {"version": 1}},
        {"id": 1, "result": ["current response"]},
    ]
    writes = []
    stdout = io.BytesIO(b"".join(Client.frame(m) for m in messages))
    client.process = SimpleNamespace(
        stdout=stdout,
        stdin=SimpleNamespace(
            write=lambda data: writes.append(data), flush=client._read
        ),
    )
    decoder = json.loads
    decode_clock_calls = []
    with patch(
        "protocol.time.perf_counter_ns",
        side_effect=[10_000_000, 11_000_000, 12_000_000, 13_000_000, 14_000_000],
    ) as clock:

        def decode(data):
            decode_clock_calls.append(clock.call_count)
            return decoder(data)

        with patch("protocol.json.loads", side_effect=decode):
            result, elapsed = client.request(
                "textDocument/definition",
                {},
                changes=[
                    {"method": "textDocument/didChange", "params": {"version": 2}}
                ],
            )
    assert result == ["current response"]
    assert elapsed == 3
    assert decode_clock_calls == [2, 3, 4]
    assert len(writes) == 1
    assert writes[0].index(b"textDocument/didChange") < writes[0].index(
        b"textDocument/definition"
    )


def test_short_response_body_is_a_crash_not_a_success():
    client = object.__new__(Client)
    client.messages = queue.Queue()
    client.process = SimpleNamespace(
        stdout=io.BytesIO(b"Content-Length: 100\r\n\r\n{}")
    )
    client._read()
    error, received = client.messages.get_nowait()
    assert isinstance(error, EOFError)
    assert "short LSP body" in str(error)
    assert received > 0


def test_scaled_plan_binds_fixture_and_rejects_changed_binary(tmp_path, monkeypatch):
    binary = tmp_path / "binary"
    binary.write_bytes(b"plan-only executable witness")
    plan_path = tmp_path / "plan.json"
    arguments = [
        "benchmark.py",
        "--binary",
        str(binary),
        "--plan",
        str(plan_path),
        "--output",
        str(tmp_path / "result.json"),
        "--classes",
        "1250",
        "--blocks",
        "2",
    ]
    monkeypatch.setattr("sys.argv", [*arguments, "--plan-only"])
    benchmark.main()
    plan = json.loads(plan_path.read_text())
    assert plan["classes"] == 1250
    assert len(plan["order"]) == 16

    # Replaying uses the saved scale even when the CLI has its default scale.
    # Stop before starting a process, after checking actual generated bytes.
    def inspect_fixture(root):
        classes = sum(
            p.read_text().count("class Noise_") for p in root.glob("classes_*.svh")
        )
        assert classes == 1250
        return plan["fixtureSha256"]

    monkeypatch.setattr(benchmark, "fixture_hashes", inspect_fixture)
    with patch.object(
        benchmark, "Client", side_effect=RuntimeError("fixture verified")
    ):
        with pytest.raises(RuntimeError, match="fixture verified"):
            benchmark.run(binary, tmp_path / "replay", "method", "completion", plan)
    binary.write_bytes(b"different executable")
    monkeypatch.setattr("sys.argv", arguments)
    with pytest.raises(AssertionError, match="binary changed after plan"):
        benchmark.main()


@pytest.mark.parametrize("option", ["--classes", "--blocks"])
def test_benchmark_rejects_empty_experiments(tmp_path, monkeypatch, option):
    monkeypatch.setattr(
        "sys.argv",
        [
            "benchmark.py",
            "--binary",
            "unused",
            "--plan",
            str(tmp_path / "plan.json"),
            "--output",
            "unused",
            option,
            "0",
            "--plan-only",
        ],
    )
    with pytest.raises(SystemExit) as error:
        benchmark.main()
    assert error.value.code == 2
    assert not (tmp_path / "plan.json").exists()


def test_real_project_oracle_preserves_unknown_macro_handles():
    from project_benchmark import normalize_project

    item = {"bufferId": 123, "documentUri": "file:///item.svh", "symbolName": "factory"}
    actual = normalize_project([item], {"sources": []}, "file:///item.svh", "")
    assert actual == [item]
    assert actual[0] is not item
    other = {**item, "bufferId": 124}
    assert normalize_project([other], {"sources": []}, "file:///item.svh", "") != actual
